const BLOCK = /<(h1|h2|h3|p|li)\b[^>]*>([\s\S]*?)<\/\1>/g;

const escapeHtml = (s) =>
  s.replace(/&(?!(amp|lt|gt|quot|#\d+);)/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// Plain text of one JSX element's children, or null if it's dynamic.
function textOf(inner) {
  // Inline links keep their text; other inline tags are unwrapped.
  let s = inner.replace(/<[A-Za-z][^>]*>|<\/[A-Za-z]+>/g, "");
  s = s.replace(/\{"\s*"\}|\{' '\}/g, " ").replace(/\{"([^"{}]*)"\}/g, "$1");
  if (/[{}]/.test(s)) return null; // depends on state/props — not static text
  s = s.replace(/\s+/g, " ").trim();
  if (/^(Loading|Thinking)\b/i.test(s)) return null; // transient UI state
  return /[A-Za-z]{3}/.test(s) ? s : null;
}

function extract(file) {
  let src = fs.readFileSync(path.join(ROOT, file), "utf8");
  src = src.replace(/<Helmet>[\s\S]*?<\/Helmet>/g, "").replace(/\{\/\*[\s\S]*?\*\/\}/g, "");
  const out = [];
  for (const [, tag, inner] of src.matchAll(BLOCK)) {
    // Skip containers whose children are other blocks (e.g. <li><p>…</p></li>).
    if (/<(h1|h2|h3|p|li)\b/.test(inner)) continue;
    const text = textOf(inner);
    if (text) out.push({ tag, text });
  }
  return out;
}

function render(blocks) {
  let html = "";
  let inList = false;
  for (const { tag, text } of blocks) {
    if (tag === "li" && !inList) { html += "<ul>"; inList = true; }
    if (tag !== "li" && inList) { html += "</ul>"; inList = false; }
    // The page title is the document's only h1 (as in buildArticle()).
    const t = tag === "h1" && html.includes("<h1>") ? "h2" : tag;
    html += `<${t}>${escapeHtml(text)}</${t}>`;
  }
  if (inList) html += "</ul>";
  return html;
}

const result = {};
for (const [route, file] of Object.entries(PAGES)) {
  const blocks = extract(file);
  result[route] = `<main>${render(blocks)}</main>`;
  const words = blocks.reduce((n, b) => n + b.text.split(/\s+/).length, 0);
  console.log(`${route.padEnd(28)} ${String(blocks.length).padStart(3)} blocks ${String(words).padStart(5)} words`);
}

